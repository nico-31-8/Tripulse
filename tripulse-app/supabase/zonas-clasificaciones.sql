/* ============================================================
   TRIPULSE — Clasificaciones de zonas propias
   ============================================================

   LO QUE CAMBIA. Hasta ahora las zonas propias iban en un solo montón por
   deporte y cada zona colgaba de UNA referencia: «88–94 % de su Ritmo100».
   No cabía lo que hace un entrenador con una prueba de esfuerzo: tres hitos
   (VT1, VT2, VO2máx) y zonas que empiezan en uno y acaban en otro —una zona
   del VT1 + 15 % al VT2 − 5 %—. Tampoco cabía tener varias formas de
   clasificar el mismo deporte: la del laboratorio, la de pista, la de técnica.

   AHORA:
     · zona_clasificacion — una por cada forma de clasificar: nombre, deporte y
       de qué hitos tira. Un hito es 'app:vam' / 'app:ftp' / 'app:css' o
       'propia:<test>:<resultado>'.
     · zona_entrenador.desde / hasta — cada límite de la zona con su hito y su
       %: {"ref": "propia:9:0", "pct": 115}. Vacío = sin límite: «por debajo
       de su VT1», «por encima de su VO2máx».

   LO QUE YA HAY NO SE PIERDE. Cada grupo de ahora (las zonas de un entrenador
   que comparten deporte y referencia) pasa a ser una clasificación, y sus
   zonas a tener el mismo hito en el desde y en el hasta. Las sesiones ya
   mandadas no cambian: llevan su copia en tarea.zona_copia.

   LAS COLUMNAS DE ANTES SE QUEDAN (pct_min, pct_max, ref_definicion,
   ref_indice) y se siguen escribiendo en las zonas de un solo hito: la app
   publicada las lee hasta que se suba la nueva. Por eso pct_min y pct_max
   dejan de ser obligatorias: una zona de dos hitos no tiene «un» porcentaje.

   UNA ZONA SOLO PUEDE IR EN UNA CLASIFICACIÓN DE SU MISMO ENTRENADOR. Lo
   garantiza la clave ajena doble (id_clasificacion, id_entrenador): con la
   sencilla, cualquiera podría colgar una zona suya de la clasificación de
   otro.

   LA SIGLA, ÚNICA DENTRO DE SU CLASIFICACIÓN y no del deporte: «UMB» puede
   estar en la del laboratorio y en la de pista. Y las archivadas ya no
   bloquean la sigla: con el índice de antes, archivar «UMB» impedía crear
   otra «UMB» para siempre.

   Se puede aplicar dos veces: todo va con if not exists / drop if exists, y
   lo que migra los datos solo toca zonas que aún no tienen clasificación. */

/* == 1. La clasificación == */
create table if not exists public.zona_clasificacion (
  id            bigint generated by default as identity primary key,
  id_entrenador uuid not null references public.perfiles(id) on delete cascade,
  nombre        text not null,
  deporte       text not null default 'Carrera',
  hitos         jsonb not null default '[]'::jsonb,
  orden         integer not null default 0,
  archivada     boolean not null default false,
  created_at    timestamptz not null default now(),
  constraint zona_clasificacion_nombre check (char_length(btrim(nombre)) between 1 and 80),
  /* Una lista de hitos, cada uno con la forma de siempre. Doce de techo: más
     que eso no es una clasificación, es un error de alguien. */
  constraint zona_clasificacion_hitos check (
    jsonb_typeof(hitos) = 'array'
    and jsonb_array_length(hitos) <= 12
    and not jsonb_path_exists(hitos,
      '$[*] ? (@.type() != "string" || !(@ like_regex "^(app:(vam|ftp|css)|propia:[0-9]+:[0-9]+)$"))')
  ),
  constraint zona_clasificacion_id_dueno unique (id, id_entrenador)
);

create index if not exists idx_zona_clasificacion_suyas
  on public.zona_clasificacion (id_entrenador, orden) where archivada = false;

alter table public.zona_clasificacion enable row level security;
revoke all on public.zona_clasificacion from anon;
grant select, insert, update, delete on public.zona_clasificacion to authenticated;

/* Las mismas dos reglas que zona_entrenador: las tuyas, todo; las de tu
   dirección (tu director o los entrenadores que diriges), solo leerlas. */
drop policy if exists zona_clasificacion_suya on public.zona_clasificacion;
create policy zona_clasificacion_suya on public.zona_clasificacion for all to authenticated
  using (id_entrenador = (select auth.uid()))
  with check (id_entrenador = (select auth.uid()));

drop policy if exists zona_clasificacion_socios on public.zona_clasificacion;
create policy zona_clasificacion_socios on public.zona_clasificacion for select to authenticated
  using (id_entrenador in (select socios_de_direccion()));

/* == 2. Las zonas: a qué clasificación van y sus dos límites == */
alter table public.zona_entrenador
  add column if not exists id_clasificacion bigint,
  add column if not exists desde jsonb,
  add column if not exists hasta jsonb;

alter table public.zona_entrenador
  alter column pct_min drop not null,
  alter column pct_max drop not null;

alter table public.zona_entrenador drop constraint if exists zona_entrenador_clasificacion_fkey;
alter table public.zona_entrenador add constraint zona_entrenador_clasificacion_fkey
  foreign key (id_clasificacion, id_entrenador)
  references public.zona_clasificacion (id, id_entrenador) on delete cascade;

/* Un límite es {"ref": <hito>, "pct": <número mayor que 0>}, o nada. Con CASE
   y no con AND: Postgres no promete el orden de un AND, y el cast de un pct
   que no fuera número reventaría en vez de suspender la comprobación. */
alter table public.zona_entrenador drop constraint if exists zona_entrenador_desde_valido;
alter table public.zona_entrenador add constraint zona_entrenador_desde_valido check (
  case
    when desde is null then true
    when jsonb_typeof(desde) <> 'object' then false
    when jsonb_typeof(desde->'ref') <> 'string' or jsonb_typeof(desde->'pct') <> 'number' then false
    else (desde->>'ref') ~ '^(app:(vam|ftp|css)|propia:[0-9]+:[0-9]+)$' and (desde->>'pct')::numeric > 0
  end
);

alter table public.zona_entrenador drop constraint if exists zona_entrenador_hasta_valido;
alter table public.zona_entrenador add constraint zona_entrenador_hasta_valido check (
  case
    when hasta is null then true
    when jsonb_typeof(hasta) <> 'object' then false
    when jsonb_typeof(hasta->'ref') <> 'string' or jsonb_typeof(hasta->'pct') <> 'number' then false
    else (hasta->>'ref') ~ '^(app:(vam|ftp|css)|propia:[0-9]+:[0-9]+)$' and (hasta->>'pct')::numeric > 0
  end
);

/* Una zona sin ningún límite sería «todo»: no es una zona. */
alter table public.zona_entrenador drop constraint if exists zona_entrenador_algun_limite;
alter table public.zona_entrenador add constraint zona_entrenador_algun_limite check (
  id_clasificacion is null or desde is not null or hasta is not null
);

create index if not exists zona_entrenador_clasificacion_idx
  on public.zona_entrenador (id_clasificacion) where id_clasificacion is not null;

/* == 3. Lo que ya hay: cada grupo pasa a ser una clasificación == */
do $migrar$
declare
  g record;
  _id bigint;
  _ref text;
  _nombre text;
begin
  for g in
    select z.id_entrenador, z.deporte, z.ref_definicion, z.ref_indice,
           min(z.orden) as orden, bool_and(z.archivada) as archivada
      from public.zona_entrenador z
     where z.id_clasificacion is null
     group by z.id_entrenador, z.deporte, z.ref_definicion, z.ref_indice
     order by z.id_entrenador, z.deporte, min(z.orden)
  loop
    _ref := case
      when g.ref_definicion is not null then 'propia:' || g.ref_definicion || ':' || g.ref_indice
      when g.deporte = 'Ciclismo' then 'app:ftp'
      when g.deporte like 'Nat%' then 'app:css'
      else 'app:vam'
    end;

    /* El nombre, el de la cabecera del grupo de antes: «6x100 · Ritmo100», o
       «Zonas sobre el CSS» si colgaban de la referencia de la app. */
    if g.ref_definicion is not null then
      select left(btrim(d.nombre || coalesce(' · ' || coalesce(
               d.resultados -> g.ref_indice ->> 'nombre',
               d.modelo -> 'resultados' -> g.ref_indice ->> 'nombre'), '')), 80)
        into _nombre
        from public.test_definicion d where d.id = g.ref_definicion;
    else
      _nombre := case _ref
        when 'app:ftp' then 'Zonas sobre el FTP'
        when 'app:css' then 'Zonas sobre el CSS'
        else 'Zonas sobre la VAM'
      end;
    end if;
    if coalesce(btrim(_nombre), '') = '' then _nombre := 'Zonas de un test'; end if;

    insert into public.zona_clasificacion (id_entrenador, nombre, deporte, hitos, orden, archivada)
    values (g.id_entrenador, _nombre, g.deporte, jsonb_build_array(_ref), g.orden, g.archivada)
    returning id into _id;

    update public.zona_entrenador z
       set id_clasificacion = _id,
           desde = case when z.pct_min > 0 then jsonb_build_object('ref', _ref, 'pct', z.pct_min) end,
           hasta = case when z.pct_max > 0 then jsonb_build_object('ref', _ref, 'pct', z.pct_max) end
     where z.id_clasificacion is null
       and z.id_entrenador = g.id_entrenador
       and z.deporte = g.deporte
       and z.ref_definicion is not distinct from g.ref_definicion
       and z.ref_indice is not distinct from g.ref_indice;
  end loop;
end
$migrar$;

/* == 4. La sigla, única dentro de su clasificación == */
drop index if exists public.idx_zona_entrenador_sigla;

create unique index if not exists idx_zona_entrenador_sigla_clasif
  on public.zona_entrenador (id_clasificacion, upper(sigla))
  where archivada = false and id_clasificacion is not null;

/* Las sueltas -las que guarde la app publicada hasta que se suba la nueva-
   siguen con la regla de antes, para no permitir dos «UMB» sueltas. */
create unique index if not exists idx_zona_entrenador_sigla_suelta
  on public.zona_entrenador (id_entrenador, deporte, upper(sigla))
  where archivada = false and id_clasificacion is null;
