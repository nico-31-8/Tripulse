/* ============================================================
   Valoración de movimiento · FMS y Nine Test (el analizador de vídeo)
   ============================================================
   Lo que el entrenador valora mirando el movimiento, en la pestaña «Movimiento»
   de Tests. Las pruebas, sus criterios y las reglas para puntuar viven en
   lib/baterias-movimiento.ts; aquí, solo lo que se guarda.

   EL VÍDEO NO SE GUARDA: se analiza en el propio dispositivo. Se guarda la nota
   de cada prueba (una fila por lado), lo que se marcó de cada criterio, las
   medidas, lo dibujado y, si el deportista ha dado su permiso, el FOTOGRAMA
   anotado, como imagen en el almacén privado «fotogramas».

   EL PERMISO lo marca el entrenador en la ficha del deportista
   (`permiso_fotogramas_en`). Sin él se guardan las notas, pero la base no deja
   subir la imagen: no depende de que la pantalla se acuerde.

   QUIÉN VE QUÉ: lo mismo que el resto de sus tests (auth_dep_ids: el propio
   deportista, su entrenador y el director al que se lo haya abierto). ESCRIBIR,
   todos menos el propio deportista: la nota la pone quien le valora. Salvo que
   sea su propio entrenador (quien se entrena a sí mismo), que entonces sí.

   PARA TODOS LOS DEMÁS NO CAMBIA NADA: dos columnas nuevas en `deportista` que
   nacen vacías, dos tablas nuevas y un almacén nuevo.
   ============================================================ */

set local lock_timeout = '5s';

/* ---- El permiso para guardar su imagen ---- */
alter table public.deportista
  add column if not exists permiso_fotogramas_en timestamptz,
  add column if not exists permiso_fotogramas_por uuid;

comment on column public.deportista.permiso_fotogramas_en is
  'Cuándo marcó el entrenador que el deportista le ha dado permiso para guardar fotogramas de sus tests de movimiento. Null = sin permiso.';

/* ---- Una valoración: una batería pasada un día ---- */
create table if not exists public.valoracion_movimiento (
  id bigint generated by default as identity primary key,
  id_deportista bigint not null references public.deportista(id) on delete cascade,
  bateria text not null check (bateria in ('fms', 'nine')),
  fecha date not null default current_date,
  modo text not null default 'video' check (modo in ('video', 'mano')),
  notas text check (notas is null or length(notas) <= 2000),
  creada_por uuid default auth.uid(),
  /* Se toca al guardar cada prueba: es lo que dispara UN aviso por batería al
     director, y no uno por cada lado de cada prueba. */
  actualizada_en timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists valoracion_movimiento_dep on public.valoracion_movimiento (id_deportista, fecha desc);

/* ---- Sus pruebas: una fila por lado (o «unico») ---- */
create table if not exists public.valoracion_prueba (
  id bigint generated by default as identity primary key,
  id_valoracion bigint not null references public.valoracion_movimiento(id) on delete cascade,
  id_deportista bigint not null references public.deportista(id) on delete cascade,
  prueba text not null check (prueba ~ '^(fms|nine)\.[a-z_]+$'),
  lado text not null default 'unico' check (lado in ('unico', 'izq', 'der')),
  nota smallint check (nota between 0 and 3),
  dolor boolean not null default false,
  criterios jsonb check (criterios is null or jsonb_typeof(criterios) = 'object'),
  medidas jsonb check (medidas is null or jsonb_typeof(medidas) = 'array'),
  dibujo jsonb check (dibujo is null or jsonb_typeof(dibujo) = 'array'),
  vista text check (vista is null or vista in ('perfil', 'frente', 'espalda', 'atras', 'arriba')),
  fotograma text,
  created_at timestamptz not null default now(),
  unique (id_valoracion, prueba, lado)
);
create index if not exists valoracion_prueba_dep on public.valoracion_prueba (id_deportista);

/* La prueba es del mismo deportista que su valoración. Corre con los permisos
   de quien escribe, así que tampoco deja colgar una prueba de una valoración
   que no ve. */
create or replace function public.valoracion_prueba_mismo_deportista()
returns trigger language plpgsql set search_path = public as $$
begin
  if new.id_deportista is distinct from
     (select v.id_deportista from valoracion_movimiento v where v.id = new.id_valoracion) then
    raise exception 'La prueba no es del mismo deportista que su valoración' using errcode = '23514';
  end if;
  return new;
end $$;
drop trigger if exists valoracion_prueba_mismo_deportista on public.valoracion_prueba;
create trigger valoracion_prueba_mismo_deportista before insert or update on public.valoracion_prueba
  for each row execute function public.valoracion_prueba_mismo_deportista();

/* ---- Quién ve y quién escribe ---- */
alter table public.valoracion_movimiento enable row level security;
alter table public.valoracion_prueba enable row level security;

drop policy if exists valoracion_movimiento_ver on public.valoracion_movimiento;
create policy valoracion_movimiento_ver on public.valoracion_movimiento for select to authenticated
  using (id_deportista in (select auth_dep_ids()));
drop policy if exists valoracion_movimiento_escribir on public.valoracion_movimiento;
create policy valoracion_movimiento_escribir on public.valoracion_movimiento for all to authenticated
  using (id_deportista in (select auth_dep_ids())
         and id_deportista not in (select d.id from deportista d where d.id_usuario = auth.uid() and d.id_entrenador is distinct from auth.uid()))
  with check (id_deportista in (select auth_dep_ids())
         and id_deportista not in (select d.id from deportista d where d.id_usuario = auth.uid() and d.id_entrenador is distinct from auth.uid()));

drop policy if exists valoracion_prueba_ver on public.valoracion_prueba;
create policy valoracion_prueba_ver on public.valoracion_prueba for select to authenticated
  using (id_deportista in (select auth_dep_ids()));
drop policy if exists valoracion_prueba_escribir on public.valoracion_prueba;
create policy valoracion_prueba_escribir on public.valoracion_prueba for all to authenticated
  using (id_deportista in (select auth_dep_ids())
         and id_deportista not in (select d.id from deportista d where d.id_usuario = auth.uid() and d.id_entrenador is distinct from auth.uid()))
  with check (id_deportista in (select auth_dep_ids())
         and id_deportista not in (select d.id from deportista d where d.id_usuario = auth.uid() and d.id_entrenador is distinct from auth.uid()));

revoke all on public.valoracion_movimiento, public.valoracion_prueba from anon;
grant select, insert, update, delete on public.valoracion_movimiento, public.valoracion_prueba to authenticated;

/* ---- El aviso al director: uno por batería ---- */
drop trigger if exists trg_cambio_director on public.valoracion_movimiento;
create trigger trg_cambio_director after insert or delete or update on public.valoracion_movimiento
  for each row execute function registrar_cambio_director('test', 'true');

/* ---- El almacén de los fotogramas ----
   Privado. La primera carpeta de cada archivo es el id del deportista:
   «{id_deportista}/{id_valoracion}/{prueba}-{lado}.jpg». Leer, quien tiene
   acceso a ese deportista; subir, cambiar o borrar, lo mismo menos el propio
   deportista, y subir solo con su permiso marcado. */
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fotogramas', 'fotogramas', false, 3145728, array['image/jpeg', 'image/webp', 'image/png'])
on conflict (id) do update
  set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists fotogramas_ver on storage.objects;
create policy fotogramas_ver on storage.objects for select to authenticated
  using (bucket_id = 'fotogramas'
         and (storage.foldername(name))[1] in (select a::text from auth_dep_ids() a));

drop policy if exists fotogramas_subir on storage.objects;
create policy fotogramas_subir on storage.objects for insert to authenticated
  with check (bucket_id = 'fotogramas'
         and (storage.foldername(name))[1] in (select a::text from auth_dep_ids() a)
         and (storage.foldername(name))[1] not in (select d.id::text from public.deportista d where d.id_usuario = auth.uid() and d.id_entrenador is distinct from auth.uid())
         and exists (select 1 from public.deportista d
                      where d.id::text = (storage.foldername(name))[1] and d.permiso_fotogramas_en is not null));

drop policy if exists fotogramas_cambiar on storage.objects;
create policy fotogramas_cambiar on storage.objects for update to authenticated
  using (bucket_id = 'fotogramas'
         and (storage.foldername(name))[1] in (select a::text from auth_dep_ids() a)
         and (storage.foldername(name))[1] not in (select d.id::text from public.deportista d where d.id_usuario = auth.uid() and d.id_entrenador is distinct from auth.uid()))
  with check (bucket_id = 'fotogramas'
         and (storage.foldername(name))[1] in (select a::text from auth_dep_ids() a)
         and exists (select 1 from public.deportista d
                      where d.id::text = (storage.foldername(name))[1] and d.permiso_fotogramas_en is not null));

drop policy if exists fotogramas_borrar on storage.objects;
create policy fotogramas_borrar on storage.objects for delete to authenticated
  using (bucket_id = 'fotogramas'
         and (storage.foldername(name))[1] in (select a::text from auth_dep_ids() a)
         and (storage.foldername(name))[1] not in (select d.id::text from public.deportista d where d.id_usuario = auth.uid() and d.id_entrenador is distinct from auth.uid()));

notify pgrst, 'reload schema';
